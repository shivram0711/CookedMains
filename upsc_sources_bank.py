def add_custom_source(paper: str, source_text: str) -> bool:
    """Helper function allowing programmatic addition of custom sources."""
    paper_key = paper.strip().upper()
    if paper_key in USER_CUSTOM_SOURCES:
        USER_CUSTOM_SOURCES[paper_key].append(source_text.strip())
        return True
    return False


